// Compiles contracts/LaunchDeskEscrow.cash and writes the artifact the server imports.
// Run: npm run contracts
import { compileFile } from "cashc";
import { writeFileSync } from "node:fs";

const src = new URL("./LaunchDeskEscrow.cash", import.meta.url);
const artifact = compileFile(src);
artifact.updatedAt = "2026-11-16T00:00:00.000Z"; // fixed: keeps the generated file stable between builds
writeFileSync(new URL("./LaunchDeskEscrow.json", import.meta.url), JSON.stringify(artifact, null, 2) + "\n");
writeFileSync(
  new URL("../server/escrow/artifact.ts", import.meta.url),
  `// GENERATED by contracts/build.mjs from contracts/LaunchDeskEscrow.cash. Do not edit.\n` +
    `export const escrowArtifact = ${JSON.stringify(artifact, null, 2)} as const;\n`,
);
console.log(`LaunchDeskEscrow: ${artifact.bytecode.split(" ").length} ops, compiler ${artifact.compiler.version}`);
