// Compiles the escrow contracts and writes the artifacts the server imports.
//   v1: contracts/LaunchDeskEscrow.cash   -> LaunchDeskEscrow.json   + server/escrow/artifact.ts    (every order so far)
//   v2: contracts/LaunchDeskEscrowV2.cash -> LaunchDeskEscrowV2.json + server/escrow/artifact-v2.ts (receipt NFT, ESCROW_V2=1)
// Run: npm run contracts
import { compileFile } from "cashc";
import { writeFileSync } from "node:fs";

for (const [name, out, exportName] of [
  ["LaunchDeskEscrow", "artifact.ts", "escrowArtifact"],
  ["LaunchDeskEscrowV2", "artifact-v2.ts", "escrowArtifactV2"],
]) {
  const artifact = compileFile(new URL(`./${name}.cash`, import.meta.url));
  artifact.updatedAt = "2026-11-16T00:00:00.000Z"; // fixed: keeps the generated file stable between builds
  writeFileSync(new URL(`./${name}.json`, import.meta.url), JSON.stringify(artifact, null, 2) + "\n");
  writeFileSync(
    new URL(`../server/escrow/${out}`, import.meta.url),
    `// GENERATED by contracts/build.mjs from contracts/${name}.cash. Do not edit.\n` +
      `export const ${exportName} = ${JSON.stringify(artifact, null, 2)} as const;\n`,
  );
  console.log(`${name}: ${artifact.bytecode.split(" ").length} ops, compiler ${artifact.compiler.version}`);
}
